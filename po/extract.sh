#!/bin/sh
# Regenerate po/sumi.pot from the app's QML/C++ and the daemon's display
# strings, then merge it into every po/<lang>.po.
#
#   po/extract.sh        (from anywhere; needs cargo, xgettext, msgcat, msgmerge)
set -eu
cd "$(dirname "$0")/.."
# Daemon-supplied labels: generated as i18n() calls so xgettext sees them.
{
    echo "// Generated by po/extract.sh from \`sumi strings\` — do not edit."
    echo "// Labels the daemon sends to the app (and its own notification texts)."
    cargo run -q -p sumi -- strings | sed 's/\\/\\\\/g; s/"/\\"/g; s/.*/i18n("&");/'
} > po/daemon-strings.cpp
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
# QML through the C++ lexer, as KDE's Messages.sh scripts do.
xgettext --from-code=UTF-8 -L C++ -ki18n:1 -ki18nc:1c,2 -ki18np:1,2 -ki18ncp:1c,2,3 \
    --add-comments=i18n: -o "$tmp/qml.pot" crates/sumi-gui/qml/*.qml
xgettext --from-code=UTF-8 -L C++ -ki18n:1 -ki18nc:1c,2 \
    --add-comments=i18n: -o "$tmp/cpp.pot" crates/sumi-gui/src/*.cpp po/daemon-strings.cpp
# The menu entry's name, comment and keywords (merged back by msgfmt --desktop).
xgettext --from-code=UTF-8 -L Desktop -k -kGenericName -kComment -kKeywords \
    -o "$tmp/desktop.pot" contrib/io.github.jenaridev.sumi.desktop
msgcat --use-first "$tmp/qml.pot" "$tmp/cpp.pot" "$tmp/desktop.pot" -o "$tmp/all.pot"
# Package header (xgettext leaves placeholders).
sed -e 's/^"Project-Id-Version: PACKAGE VERSION\\n"/"Project-Id-Version: sumi\\n"/' \
    -e 's/^"Content-Type: text\/plain; charset=CHARSET\\n"/"Content-Type: text\/plain; charset=UTF-8\\n"/' \
    -e '/^"POT-Creation-Date:/d' -e '/^"PO-Revision-Date:/d' \
    "$tmp/all.pot" > po/sumi.pot
for po in po/*.po; do
    [ -e "$po" ] || continue
    msgmerge --quiet --update --backup=none "$po" po/sumi.pot
done
echo "po/sumi.pot: $(grep -c '^msgid ' po/sumi.pot) messages"
