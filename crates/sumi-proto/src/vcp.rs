//! VCP code names for ASUS monitors using the "new VCP" scheme (0xEF major 2),
//! as DisplayWidget Center labels them on Gaming-line models.

/// Short human-readable name for a VCP code.
pub fn name(code: u8) -> &'static str {
    match code {
        0x02 => "new control value",
        0x04 => "restore factory defaults",
        0x05 => "restore brightness/contrast",
        0x08 => "restore colour defaults",
        0x10 => "brightness",
        0x12 => "contrast",
        0x14 => "colour temperature preset",
        0x16 => "red gain",
        0x18 => "green gain",
        0x1A => "blue gain",
        0x52 => "active control",
        0x59 => "saturation red",
        0x5A => "saturation yellow",
        0x5B => "saturation green",
        0x5C => "saturation cyan",
        0x5D => "saturation blue",
        0x5E => "saturation magenta",
        0x5F => "HDR adjustment (unexposed)",
        0x60 => "input source",
        0x61 => "DisplayPort stream? (unconfirmed)",
        0x62 => "audio volume",
        0x6C => "black level red (unadvertised)",
        0x6E => "black level green (unadvertised)",
        0x70 => "black level blue (unadvertised)",
        0x72 => "gamma (high byte: (v+100)/100)",
        0x87 => "sharpness",
        0x8A => "saturation",
        0x8D => "audio mute",
        0x90 => "hue",
        0xAC => "horizontal frequency",
        0xAE => "vertical frequency",
        0xB2 => "flat panel sub-pixel layout",
        0xB6 => "display technology type",
        0xC0 => "display usage time",
        0xC6 => "application enable key",
        0xC8 => "display controller type",
        0xCC => "OSD language",
        0xD6 => "power mode",
        0xDC => "GameVisual mode",
        0xDF => "VCP version",
        0xE0 => "overdrive",
        0xE1 => "power saving",
        0xE2 => "HDR mode (hi: family, lo: mode)",
        0xE3 => "GamePlus crosshair",
        0xE4 => "GamePlus timer",
        0xE5 => "shadow boost",
        0xE6 => "blue light filter",
        0xE7 => "GamePlus display alignment",
        0xE8 => "GamePlus position (write-only)",
        0xE9 => "unknown E9 (OSD timing?)",
        0xEA => "GamePlus FPS counter",
        0xEB => "OSD instruction (write-only)",
        0xEC => "reset (write-only)",
        0xED => "rest reminder / proximity? (unconfirmed)",
        0xEE => "power saving (old scheme) / ELMB?",
        0xEF => "ASUS VCP version + vendor",
        0xF2 => "Aura / black level signal? (unconfirmed)",
        0xF3 => "KVM",
        0xF4 => "PIP/PBP mode",
        0xF5 => "PIP/PBP sources (lo: A, hi: B)",
        0xF6 => "PIP/PBP GameVisual (lo: A, hi: B)",
        0xF7 => "unknown F7",
        0xF8 => "OLED care reminder (hours)",
        0xF9 => "OLED screen move",
        0xFA => "unknown FA (customized setting?)",
        0xFB => "OSD shortcuts (hi: 1, lo: 2)",
        0xFC => "toggle settings 1 (bitfield)",
        0xFD => "toggle settings 2 (OLED bitfield)",
        0xFF => "firmware version",
        _ => "",
    }
}

/// Codes that answer Get with "unsupported" because they are write-only.
pub const WRITE_ONLY: &[u8] = &[0x04, 0x05, 0x08, 0xE8, 0xEB, 0xEC];

/// Readable codes the PG32UCDM3 answers but does not advertise.
pub const UNADVERTISED_READABLE: &[u8] = &[0x6C, 0x6E, 0x70];
