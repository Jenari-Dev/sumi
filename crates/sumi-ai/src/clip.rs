//! CLIP zero-shot scene classifier (OpenAI CLIP ViT-B/32 vision encoder, ONNX,
//! run with tract — pure Rust, CPU). Text embeddings of the prompts are
//! precomputed and loaded from JSON.

use std::path::Path;

use anyhow::{bail, Context, Result};
use serde::{Deserialize, Serialize};
use tract_onnx::prelude::*;

use crate::decision::{Observation, Scene};
use crate::preprocess::{self, Frame};
use crate::prompts::{Label, PROMPTS};

/// CLIP's learned logit scale (exp(4.6052) = 100).
const LOGIT_SCALE: f32 = 100.0;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PromptEmbedding {
    pub text: String,
    /// L2-normalised text embedding.
    pub embedding: Vec<f32>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PromptFile {
    /// Model the embeddings were made with (must match the vision model).
    pub model: String,
    pub prompts: Vec<PromptEmbedding>,
}

type Plan = SimplePlan<TypedFact, Box<dyn TypedOp>, Graph<TypedFact, Box<dyn TypedOp>>>;

pub struct Clip {
    plan: Plan,
    /// One averaged, normalised vector per label.
    text: Vec<(Label, Vec<f32>)>,
}

fn l2_normalise(v: &mut [f32]) {
    let n = v.iter().map(|x| x * x).sum::<f32>().sqrt();
    if n > 0.0 {
        v.iter_mut().for_each(|x| *x /= n);
    }
}

/// Match the shipped embeddings to the current prompt list by text and
/// average each label's prompts into one class vector (prompt ensembling).
pub fn bind_prompts(file: &PromptFile) -> Result<Vec<(Label, Vec<f32>)>> {
    let mut classes: Vec<(Label, Vec<f32>)> = Vec::new();
    for (label, text) in PROMPTS {
        let e = file
            .prompts
            .iter()
            .find(|p| p.text == *text)
            .with_context(|| format!("no embedding for prompt {text:?}; regenerate prompt-embeddings.json"))?;
        let mut v = e.embedding.clone();
        l2_normalise(&mut v);
        match classes.iter_mut().find(|(l, _)| l == label) {
            Some((_, acc)) => acc.iter_mut().zip(&v).for_each(|(a, b)| *a += b),
            None => classes.push((*label, v)),
        }
    }
    classes.iter_mut().for_each(|(_, v)| l2_normalise(v));
    Ok(classes)
}

/// Turn cosine similarities with the class vectors into the decision
/// engine's observation.
pub fn observation(classes: &[(Label, Vec<f32>)], image: &[f32]) -> Observation {
    let logit = |v: &[f32]| LOGIT_SCALE * v.iter().zip(image).map(|(a, b)| a * b).sum::<f32>();
    let softmax = |items: &[(Label, f32)]| -> Vec<(Label, f64)> {
        let max = items.iter().map(|(_, x)| *x).fold(f32::MIN, f32::max);
        let exps: Vec<f64> = items.iter().map(|(_, x)| ((x - max) as f64).exp()).collect();
        let sum: f64 = exps.iter().sum();
        items.iter().zip(exps).map(|((l, _), e)| (*l, e / sum)).collect()
    };
    let scenes: Vec<(Label, f32)> = classes.iter().filter(|(l, _)| matches!(l, Label::Scene(_))).map(|(l, v)| (*l, logit(v))).collect();
    let gates: Vec<(Label, f32)> =
        classes.iter().filter(|(l, _)| matches!(l, Label::Game | Label::NotGame)).map(|(l, v)| (*l, logit(v))).collect();
    let scene_p = softmax(&scenes);
    let scores: Vec<(Scene, f64)> = Scene::ALL
        .iter()
        .map(|&s| (s, scene_p.iter().find(|(l, _)| *l == Label::Scene(s)).map(|(_, p)| *p).unwrap_or(0.0) * 100.0))
        .collect();
    let is_game = softmax(&gates).iter().find(|(l, _)| *l == Label::Game).map(|(_, p)| *p).unwrap_or(0.0);
    let confidence = scores.iter().map(|(_, s)| *s).fold(0.0, f64::max) / 100.0;
    Observation { scores, is_game, confidence }
}

/// Prompt embeddings shipped with Sumi (generated by `sumi-embed-prompts`).
pub const SHIPPED_PROMPTS: &str = include_str!("../data/prompt-embeddings.json");

pub fn shipped_prompts() -> Result<PromptFile> {
    let f: PromptFile = serde_json::from_str(SHIPPED_PROMPTS).context("parsing prompt-embeddings.json")?;
    if f.prompts.is_empty() {
        bail!("this build has no prompt embeddings yet (run sumi-embed-prompts)");
    }
    Ok(f)
}

impl Clip {
    /// Load the vision encoder and the prompt embeddings.
    pub fn load(vision_onnx: &Path, prompts: &PromptFile) -> Result<Self> {
        let text = bind_prompts(prompts)?;
        let plan = tract_onnx::onnx()
            .model_for_path(vision_onnx)
            .with_context(|| format!("reading {}", vision_onnx.display()))?
            .with_input_fact(0, f32::fact([1, 3, preprocess::SIZE, preprocess::SIZE]).into())?
            .with_output_names(["image_embeds"])?
            .into_optimized()?
            .into_runnable()?;
        Ok(Clip { plan, text })
    }

    /// The L2-normalised image embedding of a frame.
    pub fn embed(&self, frame: &Frame) -> Result<Vec<f32>> {
        let pixels = preprocess::to_tensor(frame);
        let input = Tensor::from_shape(&[1, 3, preprocess::SIZE, preprocess::SIZE], &pixels)?;
        let out = self.plan.run(tvec!(input.into()))?;
        let mut v: Vec<f32> = out[0].to_array_view::<f32>()?.iter().copied().collect();
        if v.len() != self.text.first().map(|t| t.1.len()).unwrap_or(0) {
            bail!("image embedding has {} dims, prompts have {}", v.len(), self.text[0].1.len());
        }
        l2_normalise(&mut v);
        Ok(v)
    }

    pub fn classify(&self, frame: &Frame) -> Result<Observation> {
        Ok(observation(&self.text, &self.embed(frame)?))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn observation_scores_classes() {
        // Two dims: x = "game-ish FPS", y = "desktop".
        let fps = Label::Scene(Scene::Fps);
        let office = Label::Scene(Scene::Office);
        let text = vec![
            (fps, vec![1.0, 0.0]),
            (office, vec![0.0, 1.0]),
            (Label::Game, vec![1.0, 0.0]),
            (Label::NotGame, vec![0.0, 1.0]),
        ];
        let o = observation(&text, &[1.0, 0.0]);
        let fps_score = o.scores.iter().find(|(s, _)| *s == Scene::Fps).unwrap().1;
        assert!(fps_score > 99.0, "{fps_score}");
        assert!(o.is_game > 0.99 && o.confidence > 0.99);
        let o = observation(&text, &[0.0, 1.0]);
        assert!(o.scores.iter().find(|(s, _)| *s == Scene::Office).unwrap().1 > 99.0);
        assert!(o.is_game < 0.01);
    }
}
